"""Collect every headline number of the report from results/*.json into results/summary.md."""
import json

import numpy as np

from autogear.paths import RESULTS

KINDS = ("R0", "R1", "RT", "GBDT", "LIN", "TAB", "MLP", "RF")


def load(name):
    p = RESULTS / name
    return json.loads(p.read_text()) if p.exists() else None


def wmean(tests, kind, key="agree_pm1", group=None):
    rows = [r for r in tests.values() if group is None or r.get("group") == group]
    h = np.array([r["hours"] for r in rows])
    return float((h * np.array([r[kind][key] for r in rows])).sum() / h.sum())


def pct(x):
    return f"{100 * x:.1f} %"


if __name__ == "__main__":
    out = ["# Headline numbers (generated by scripts/11_summarise_results.py)", ""]
    ds, val = load("dataset_summary.json"), load("gear_reconstruction_validation.json")
    if ds:
        out += [f"- dataset: {ds['hours']} h, {ds['riders']} riders, {ds['rides']} rides, "
                f"shift share {ds['shift_share'] * 100:.2f} %"]
    if val:
        out += [f"- gear reconstruction (Di2): state accuracy {pct(val['state_accuracy'])} of pedalling seconds, "
                f"events precision {val['event_precision']:.2f} recall {val['event_recall']:.2f} "
                f"({val['true_shifts']} true shifts), development x teeth {val['development_x_teeth']}"]
    tp = load("target_policies.json")
    ev = load("event_classifier.json")
    if tp:
        T = tp["tests"]
        out += ["", "## Within-rider protocol, 14 tests", "",
                "| policy | within one gear | Inria | single-ride | exact | shifts/h | reversals | cadence band | median size (B) | wins vs best table |",
                "|---|---|---|---|---|---|---|---|---|---|"]
        out += [f"| rider | 100 % | | | 100 % | {wmean(T, 'rider', 'shifts_per_h'):.0f} | "
                f"{pct(wmean(T, 'rider', 'reversal'))} | {pct(wmean(T, 'rider', 'cadence_band'))} | | |"]
        best_table = {n: max(r[k]["agree_pm1"] for k in ("R0", "R1", "RT")) for n, r in T.items()}
        for k in KINDS:
            wins = sum(r[k]["agree_pm1"] > best_table[n] for n, r in T.items())
            size = np.median([r[k]["size_bytes"] for r in T.values()])
            out += [f"| {k} | {pct(wmean(T, k))} | {pct(wmean(T, k, group='inria'))} | "
                    f"{pct(wmean(T, k, group='single-ride'))} | {pct(wmean(T, k, 'exact'))} | "
                    f"{wmean(T, k, 'shifts_per_h'):.0f} | {pct(wmean(T, k, 'reversal'))} | "
                    f"{pct(wmean(T, k, 'cadence_band'))} | {size:.0f} | {wins}/14 |"]
        out += [f"| never shift | {pct(wmean(T, 'never_shift'))} | | | {pct(wmean(T, 'never_shift', 'exact'))} | 0 | | "
                f"{pct(wmean(T, 'never_shift', 'cadence_band'))} | | |"]
        margins = sorted((r["GBDT"]["agree_pm1"] - best_table[n]) * 100 for n, r in T.items())
        out += ["", f"- GBDT margin over best table per test: median {np.median(margins):+.1f} points, "
                f"min {margins[0]:+.1f}, max {margins[-1]:+.1f}"]
        rt_r1 = [(r["RT"]["agree_pm1"] - r["R1"]["agree_pm1"]) * 100 for r in T.values()]
        out += [f"- RT - R1: overall {100 * (wmean(T, 'RT') - wmean(T, 'R1')):+.1f} points (duration-weighted); "
                f"per test min {min(rt_r1):+.1f}, max {max(rt_r1):+.1f}"]
        for other in ("LIN", "TAB", "MLP", "RF"):
            w = sum(r["GBDT"]["agree_pm1"] > r[other]["agree_pm1"] for r in T.values())
            out += [f"- GBDT beats {other} on {w}/14 tests"]
        out += [f"- frozen settings: {tp['frozen']}"]
    if ev:
        E = ev["tests"]
        h = np.array([r["hours"] for r in E.values()])
        g = lambda key, grp=None: float(sum(r["hours"] * r["EV"][key] for r in E.values() if grp in (None, r["group"]))
                                        / sum(r["hours"] for r in E.values() if grp in (None, r["group"])))
        off = lambda key, grp=None: float(sum(r["hours"] * r["EV"]["offline"][key] for r in E.values() if grp in (None, r["group"]))
                                          / sum(r["hours"] for r in E.values() if grp in (None, r["group"])))
        out += ["", "## Event classifier", "",
                f"- within one gear: all {pct(g('agree_pm1'))}, Inria {pct(g('agree_pm1', 'inria'))}, "
                f"single-ride {pct(g('agree_pm1', 'single-ride'))}; exact {pct(g('exact'))}; band {pct(g('cadence_band'))}",
                f"- shifts/h: all {g('shifts_per_h'):.0f}, Inria {g('shifts_per_h', 'inria'):.0f}, "
                f"single-ride {g('shifts_per_h', 'single-ride'):.0f}; reversals all {pct(g('reversal'))}, "
                f"Inria {pct(g('reversal', 'inria'))}, single-ride {pct(g('reversal', 'single-ride'))}",
                f"- offline (means weighted by duration): PR-AUC {off('pr_auc'):.3f} (prevalence {off('prevalence'):.3f}); "
                f"Inria {off('pr_auc', 'inria'):.3f} ({off('prevalence', 'inria'):.3f}); "
                f"single {off('pr_auc', 'single-ride'):.3f} ({off('prevalence', 'single-ride'):.3f})",
                f"- event F1: all {off('event_f1'):.2f}, Inria {off('event_f1', 'inria'):.2f}, single {off('event_f1', 'single-ride'):.2f}",
                f"- correlation(event F1, closed-loop agreement) = "
                f"{np.corrcoef([r['EV']['offline']['event_f1'] for r in E.values()], [r['EV']['agree_pm1'] for r in E.values()])[0, 1]:.2f}",
                f"- median size {np.median([r['EV']['size_bytes'] for r in E.values()]):.0f} B; "
                f"Inria sizes {[r['EV']['size_bytes'] for r in E.values() if r['group'] == 'inria']}",
                f"- tests with zero shifts: {sum(r['EV']['shifts_per_h'] == 0 for r in E.values())}"]
    for name in ("timing_sweep.json", "cross_rider.json", "model_analysis.json", "firmware_export.json"):
        d = load(name)
        if d is None:
            continue
        out += ["", f"## {name}", ""]
        if name == "cross_rider.json":
            T = d["tests"]
            for k in ("R0", "R1", "RT", "GBDT"):
                out += [f"- {k}: within one gear {pct(wmean(T, k))}, shifts/h {wmean(T, k, 'shifts_per_h'):.0f}, "
                        f"reversals {pct(wmean(T, k, 'reversal'))}"]
            out += [f"- rider shifts/h {wmean(T, 'rider', 'shifts_per_h'):.0f}"]
            for n, r in T.items():
                out += [f"  - {n}: " + ", ".join(f"{k} {100 * r[k]['agree_pm1']:.1f}" for k in ("R0", "R1", "RT", "GBDT"))]
        elif name == "timing_sweep.json":
            for sec, rows in d.items():
                for key, r in rows.items():
                    out += [f"- {sec} {key}: agree {pct(r['agree_pm1'])}, shifts/h {r['shifts_per_h']:.0f}, "
                            f"rev {pct(r['reversal'])}, delay mean {r['delay_mean']:+.1f} s, "
                            f"up median {r['delay_up_median']:+.0f}, down median {r['delay_down_median']:+.0f}"]
        else:
            out += [f"- {json.dumps(d)[:1500]}"]
    (RESULTS / "summary.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))
